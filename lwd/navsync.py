"""Regenerate the area tabs of the zensical.toml nav from the taxonomy.

The hand-written part of the nav (Home, Study, Glossary) sits above the
BEGIN marker and is never touched. Between the markers, each tab lists its
areas, domains and groups in taxonomy order; pages inside a folder follow
the backlog (curriculum) order, then title order for unplanned pages.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from lwd import paths
from lwd.model import Article, Library

BEGIN = "  # BEGIN lwd nav: generated by `python -m lwd nav`; edit taxonomy.yml, not these lines"
END = "  # END lwd nav"

# Tab label -> areas, in order. A one-area tab lists that area's pages directly.
TABS = [
    ("Architecture", ["architecture", "decisions"]),
    ("Cloud", ["cloud"]),
    ("AI", ["ai"]),
    ("Security", ["security"]),
    ("Engineering", ["messaging", "data", "frontend", "devops"]),
    ("Practice", ["practice"]),
]


class NavError(Exception):
    pass


def _q(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _label(a: Article) -> str:
    """Nav label: the title before a subtitle, when that part stands on its own."""
    head, sep, _ = a.title.partition(": ")
    return head if sep and len(head) >= 12 else a.title


def _order(lib: Library) -> dict[str, int]:
    rank: dict[str, int] = {}
    for _, data in sorted(lib.backlog.items()):
        for a in data.get("articles") or []:
            page = f"{str(a.get('folder', '')).strip('/')}/{a.get('slug', '')}.md"
            rank.setdefault(page, len(rank))
    return rank


def _entries(pages: list[Article], rank: dict[str, int]) -> list[str]:
    index = [a for a in pages if a.kind == "index"]
    rest = sorted((a for a in pages if a.kind == "article"), key=lambda a: (rank.get(a.page, len(rank)), a.title.casefold()))
    return [_q(a.page) for a in index] + [f"{{ {_q(_label(a))} = {_q(a.page)} }}" for a in rest]


def _section(label: str, items: list[str], indent: int) -> list[str]:
    pad = "  " * indent
    if not items:
        return []
    lines = [f"{pad}{{ {_q(label)} = ["]
    for i, item in enumerate(items):
        lines.append(item if item.startswith(pad + "  ") else f"{pad}  {item}")
        if i < len(items) - 1:
            lines[-1] += ","
    lines.append(f"{pad}] }}")
    return ["\n".join(lines)]


def _area_items(lib: Library, area: str, indent: int, rank: dict[str, int]) -> list[str]:
    spec = lib.taxonomy.areas.get(area)
    if spec is None:
        return []
    pages = [a for a in lib.articles.values() if a.area == area and a.kind in ("article", "index")]
    items = _entries([a for a in pages if not a.domain], rank)
    for did, dlabel in spec.domains.items():
        in_domain = [a for a in pages if a.domain == did]
        sub = _entries([a for a in in_domain if not a.group], rank)
        for gid, glabel in spec.groups.get(did, {}).items():
            sub += _section(glabel, _entries([a for a in in_domain if a.group == gid], rank), indent + 1)
        items += _section(dlabel, sub, indent)
    return items


def render(lib: Library) -> str:
    rank = _order(lib)
    tabs = []
    for label, areas in TABS:
        items = []
        for area in areas:
            spec = lib.taxonomy.areas.get(area)
            if spec is None:
                continue
            if len(areas) == 1 or spec.label == label:
                items += _area_items(lib, area, 2, rank)  # the tab's own area sits directly in the tab
            else:
                items += _section(spec.label, _area_items(lib, area, 3, rank), 2)
        tabs += _section(label, items, 1)
    return ",\n".join(tabs)


def sync(lib: Library, check: bool = False) -> bool:
    """Rewrite the generated part of the nav. Returns True when it changed (or would)."""
    path = lib.config.root / paths.CONFIG_NAME
    text = path.read_text(encoding="utf-8")
    m = re.search(rf"^{re.escape(BEGIN)}\n(.*?)^{re.escape(END)}\n", text, re.S | re.M)
    if not m:
        raise NavError(f"{paths.CONFIG_NAME} has no '{BEGIN.strip()}' ... '{END.strip()}' block inside nav")
    body = render(lib)
    new = text[: m.start(1)] + (body + "\n" if body else "") + text[m.end(1):]
    if new == text:
        return False
    if not check:
        paths.atomic_write(path, new.encode("utf-8"))
    return True
