"""Helpers shared by the renderers: front matter, links, escaping, chips."""

from __future__ import annotations

import re

import yaml

from lwd import paths
from lwd.model import Library, Term

BANNER = "# GENERATED by lwd from {source}. Edit the source, not this file."


def front_matter(meta: dict, source: str) -> str:
    body = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, default_flow_style=False, width=10_000)
    return f"---\n{BANNER.format(source=source)}\n{body}---\n\n"


def link(from_page: str, to_page: str, text: str, anchor: str = "") -> str:
    href = paths.rel_link(from_page, to_page)
    return f"[{link_text(text)}]({href}{'#' + anchor if anchor else ''})"


def link_text(text: str) -> str:
    return text.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


def inline(text: str) -> str:
    """Plain text safe for inline Markdown (no raw HTML)."""
    return (text or "").replace("<", "&lt;").replace(">", "&gt;")


def cell(text: str) -> str:
    return inline(text).replace("|", "\\|").replace("\n", " ")


def html(text: str) -> str:
    return (text or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def chip(kind: str, value: str, label: str) -> str:
    return f'<span class="lwd-chip lwd-chip--{kind} lwd-chip--{kind}-{value}">{html(label)}</span>'


def status_note(status: str) -> str:
    if status == "stub":
        return '!!! warning "Stub"\n    This page is a scope outline. The full explanation has not been written yet.\n\n'
    if status == "draft":
        return '!!! info "Draft"\n    This page is in progress and has not been fully verified against primary sources yet.\n\n'
    return ""


def facet_page(facet: str, value: str) -> str:
    return f"glossary/browse/{facet}/{value}.md"


def term_link(from_page: str, lib: Library, slug: str, text: str | None = None) -> str:
    t = lib.terms.get(slug)
    if t is None:
        return inline(text or slug)
    return link(from_page, t.page, text or t.title)


def display_names(t: Term) -> list[str]:
    names = [t.title] + t.aliases + [f.name for f in t.formerly]
    return [n for n in names if n]


def plain(text: str) -> str:
    """Strip simple Markdown markup for one-line summaries."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text or "")
    text = re.sub(r"[*_`]", "", text)
    return re.sub(r"\s+", " ", text).strip()


def truncate(text: str, limit: int) -> str:
    text = plain(text)
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:") + "…"
